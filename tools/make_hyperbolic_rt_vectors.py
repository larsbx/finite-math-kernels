#!/usr/bin/env python3
"""Generate exact hyperbolic RT test vectors from independent Python formulas.

Use: python tools/make_hyperbolic_rt_vectors.py [--check]
No random sampling: the v1 corpus is a fixed, finite, inspectable table.
"""
from __future__ import annotations
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "reference"))
from hyperbolic_rt_reference import norm, polar, spread, triple_defect

OUT = ROOT / "conformance/hyperbolic_rt_v1.txt"
HEADER = "# hyperbolic-rt-v1; generated by tools/make_hyperbolic_rt_vectors.py; do not hand-edit"

def unit(p: int, i: int) -> tuple[int, ...]:
    v = [0] * 8
    v[i], v[i+4] = 1, pow(2, -1, p)
    return tuple(v)

def vector_text(x: tuple[int, ...]) -> str:
    return ",".join(map(str, x))

def render() -> str:
    lines = [HEADER]
    for p in (3, 5, 7):
        a, b, e, f = [unit(p, i) for i in range(4)]
        c = tuple((x+y) % p for x, y in zip(a, b))
        null = (1, 0, 0, 0, 0, 0, 0, 0)
        for x in (a, b, c, null):
            lines.append(f"norm\t{p}\t{vector_text(x)}\t{norm(p,x)}")
        for x,y in ((a,a),(a,b),(a,c),(b,e)):
            lines.append(f"polar\t{p}\t{vector_text(x)}\t{vector_text(y)}\t{polar(p,x,y)}")
        for x,y in ((a,b),(a,a),(a,c),(null,a),(b,e),(a,f)):
            s = spread(p,x,y)
            lines.append(f"spread\t{p}\t{vector_text(x)}\t{vector_text(y)}\t{'rejected' if s is None else s}")
        planar = (spread(p,a,b), spread(p,b,c), spread(p,c,a))
        nonplanar = (spread(p,a,b), spread(p,b,e), spread(p,e,a))
        assert all(x is not None for x in (*planar,*nonplanar))
        assert triple_defect(p,*planar) == 0
        assert triple_defect(p,*nonplanar) != 0
        for label, triple in (("planar",planar),("nonplanar",nonplanar)):
            lines.append(f"triple\t{p}\t{label}\t{triple[0]}\t{triple[1]}\t{triple[2]}\t{triple_defect(p,*triple)}")
    return "\n".join(lines)+"\n"

def main() -> int:
    expected = render()
    if sys.argv[1:] == ["--check"]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != expected:
            print("hyperbolic RT vectors drift: run tools/make_hyperbolic_rt_vectors.py", file=sys.stderr)
            return 1
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(expected, encoding="utf-8")
    return 0

if __name__ == "__main__":
    sys.exit(main())
