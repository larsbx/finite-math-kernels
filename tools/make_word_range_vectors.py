#!/usr/bin/env python3
"""Generate or verify the fixed signed machine-word range corpus.

    python tools/make_word_range_vectors.py          # render
    python tools/make_word_range_vectors.py --check  # fail on drift

The vectors are generated by the independent Python reference, NOT by the
canonical Mojo implementation; on words of at most four bits every range is
also checked against the enumerated image of its operands. Consumers replay
the file byte-for-byte; larsbx/tclmesh pins it by SHA-256.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "reference"))
from word_range_reference import OPS, apply, bounds, enumerated, make, wrap

OUT = ROOT / "conformance/word_range_v1.txt"
HEADER = "# word-range-v1; generated by tools/make_word_range_vectors.py; do not hand-edit"
WIDTHS = (1, 2, 4, 8, 16, 32)


def ranges(width: int) -> list[tuple[int, int]]:
    """Boundary ranges of the word: whole, halves, extreme points, a window."""
    lo, hi = bounds(width)
    candidates = [(lo, hi), (lo, lo), (hi, hi), (0, 0), (-1, -1), (0, hi), (lo, 0), (-3, 5)]
    return list(dict.fromkeys(c for c in candidates if make(width, *c) is not None))


def cell(r) -> str:
    return "refused" if r is None else f"{r[0]},{r[1]}"


def render() -> str:
    lines = [HEADER]
    for width in WIDTHS:
        lo, hi = bounds(width)
        for args in ((lo, hi), (lo - 1, hi), (lo, hi + 1), (1, 0), (hi, hi)):
            lines.append("\t".join(["make", str(width), *map(str, args), cell(make(width, *args))]))
        for x in (0, 1, -1, hi, lo, hi + 1, lo - 1, 1 << width, -(1 << width), 1 << 62,
                  -(1 << 62), (1 << 63) - 1, -(1 << 63)):
            lines.append("\t".join(["wrap", str(width), str(x), str(wrap(x, width))]))
        rs = ranges(width)
        for op in OPS:
            pairs = [(a, None) for a in rs] if op == "neg" else [(a, b) for a in rs for b in rs]
            for a, b in pairs:
                result = apply(op, width, a, b)
                if width <= 4:
                    assert result == enumerated(op, width, a, b), (op, width, a, b)
                lines.append("\t".join(["range", op, str(width), cell(a), "-" if b is None else cell(b),
                                        cell(result)]))
    return "\n".join(lines) + "\n"


def main(args: list[str]) -> int:
    text = render()
    if args == ["--check"]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("word-range vectors drift: run tools/make_word_range_vectors.py", file=sys.stderr)
            return 1
        return 0
    if args:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
