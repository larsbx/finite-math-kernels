#!/usr/bin/env python3
"""Generate or verify the fixed exact Gram-minor RT corpus.

    python tools/make_gram_geometry_vectors.py          # render
    python tools/make_gram_geometry_vectors.py --check  # fail on drift

The vectors are generated by the independent Python coordinate-minor
reference, NOT by the canonical Mojo implementation.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "reference"))
from gram_geometry_reference import gram2, gram3, rank_le_two, normalized_gram3, planar_defect

OUT = ROOT / "conformance/gram_geometry_v1.txt"
HEADER = "# gram-geometry-v1; generated by tools/make_gram_geometry_vectors.py; do not hand-edit"


def unit(p: int, i: int) -> tuple[int, ...]:
    a = [0] * 8
    a[i] = 1
    a[i + 4] = pow(2, -1, p)
    return tuple(a)


def add(p: int, *vectors: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(sum(v[i] for v in vectors) % p for i in range(8))


def vectors(p: int):
    x, y, z = (unit(p, i) for i in range(3))
    null = tuple(int(i == 2) for i in range(8))
    return [
        ("planar", x, y, add(p, x, y)),
        ("independent", x, y, z),
        ("radical", x, y, add(p, x, y, null)),
        ("tangent", x, add(p, x, null), y),
        ("null", x, y, null),
        ("proportional", x, y, tuple(2 * k % p for k in x)),
    ]


def value(x: int | None) -> str:
    return "rejected" if x is None else str(x)


def render() -> str:
    lines = [HEADER]
    for p in (3, 5, 7):
        for label, x, y, z in vectors(p):
            g2 = gram2(p, x, y)
            g3 = gram3(p, x, y, z)
            rank = int(rank_le_two(p, x, y, z))
            n = normalized_gram3(p, x, y, z)
            d = planar_defect(p, x, y, z)
            if label == "radical":
                assert g3 == 0 and rank == 0 and n == 0
            if label == "tangent":
                assert g2 == 0 and rank == 0
            if label == "planar":
                assert rank == 1 and d == 0
            if label == "independent":
                assert rank == 0 and g3 != 0
            lines.append("\t".join([
                "case", str(p), label,
                ",".join(map(str, x)), ",".join(map(str, y)),
                ",".join(map(str, z)), str(g2), str(g3),
                str(rank), value(n), value(d)
            ]))
    return "\n".join(lines) + "\n"


def main(args: list[str]) -> int:
    text = render()
    if args == ["--check"]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("Gram vectors drift: run tools/make_gram_geometry_vectors.py", file=sys.stderr)
            return 1
        return 0
    if args:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
